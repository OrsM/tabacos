"""python -m analyses.passthrough.run [db] -> result_passthrough* tables and report.md"""
import sys
from datetime import date, timedelta
from pathlib import Path

import sqlite_utils

from tabacos.tax import TaxRate

from .model import change_rows, summarise

HERE = Path(__file__).parent
BEFORE, AFTER = timedelta(days=14), timedelta(days=90)
FIRST_EVENT = date(2012, 1, 1)


def rate_on(rates: list[TaxRate], day: date) -> TaxRate:
    return [r for r in rates if r.effective_from <= day][-1]


def vat_on(vat: list[tuple[date, float]], day: date) -> float:
    return [p for d, p in vat if d <= day][-1]


def load(db):
    rates = [TaxRate(**{**r, "effective_from": date.fromisoformat(r["effective_from"])})
             for r in db["tax_rates"].rows_where("product = 'cigarrillos'", order_by="effective_from")]
    vat = [(date.fromisoformat(r["effective_from"]), r["vat_pct"]) for r in db["vat_rates"].rows_where(order_by="effective_from")]
    changes = [{**r, "published": date.fromisoformat(r["published"])} for r in db.query(
        """select product, published, old_price, new_price from price_changes
           where category = 'cigarrillos' and (product not like '%(%)%' or product like '%(20)%')
             and old_price between 2.0 and 9.0 and new_price between 2.0 and 9.0""")]
    return rates, vat, changes


def events(rates, vat) -> list[date]:
    """Dates on which the cigarette excise or the general VAT rate changed, from FIRST_EVENT on."""
    excise = {r.effective_from for r in rates[1:]}
    vat_days = {d for (d, p), (_, before) in zip(vat[1:], vat) if p != before}
    return sorted(d for d in excise | vat_days if d >= FIRST_EVENT)


def assign(changes: list[dict], days: list[date]) -> dict[date, list[dict]]:
    """Each change goes to the latest tax change that started no more than 14 days after it, if within 90 days."""
    out = {d: [] for d in days}
    for c in changes:
        starts = [d for d in days if d - BEFORE <= c["published"]]
        if starts and c["published"] <= starts[-1] + AFTER:
            out[starts[-1]].append(c)
    return out


def baseline(changes: list[dict], days: list[date], rates, vat) -> list[dict]:
    """Price changes outside every tax window, with the tariff unchanged: the ordinary repricing to compare with."""
    in_window = {id(c) for group in assign(changes, days).values() for c in group}
    rows = []
    for c in changes:
        if id(c) not in in_window:
            r, v = rate_on(rates, c["published"]), vat_on(vat, c["published"])
            rows += change_rows([c], r, r, v, v)
    return rows


def baseline_for(base: list[dict], year: int, min_n: int = 30) -> dict:
    """The ordinary-repricing row of `year`, or of the nearest year with at least min_n changes."""
    solid = [b for b in base if b["n"] >= min_n]
    return min(solid, key=lambda b: abs(b["year"] - year))


def money(x: float) -> str:
    return f"{x:+.3f}"


def render(per_event: list[dict], base: list[dict]) -> str:
    lines = ["# Tax pass-through on cigarette prices", "",
             "Generated by `python -m analyses.passthrough.run`. See question.md for method and limits.", "",
             "`d_net` is the change in what is left after excise and VAT (EUR per pack of 20); 0 = the tax change was passed "
             "through exactly. Regime = which part of the old tariff set the excise at the old price.", ""]
    for e in per_event:
        lines += [f"## {e['date']}: {e['what']}", ""]
        if not e["summary"]:
            lines += ["No price changes in the window.", ""]
            continue
        b = baseline_for(base, int(e["date"][:4]))
        lines += ["| Old regime | n | Median price change | Tax-implied | Median d_net (EUR/pack) | Ordinary d_net, " + str(b["year"]) + " |",
                  "|---|---|---|---|---|---|"]
        lines += [f"| {s['regime_old']} | {s['n']} | {s['median_actual_pct']:+.1f}% | {s['median_implied_pct']:+.1f}% "
                  f"| {money(s['median_d_net'])} | {money(b['median_d_net'])} |" for s in e["summary"]]
        lines += [""]
    lines += ["## Ordinary repricing: price changes outside every tax window", "",
              "The tariff did not change, so `d_net` is just the change in what is left after tax. This is the yardstick for "
              "the groups above.", "",
              "| Year | n | Median price change | Median d_net (EUR/pack) |", "|---|---|---|---|"]
    lines += [f"| {y['year']} | {y['n']} | {y['median_actual_pct']:+.1f}% | {money(y['median_d_net'])} |" for y in base]
    lines += ["", "## Notes", "",
              "- Groups with n below about 10 are anecdotes, not estimates.",
              "- Compare each event's d_net with the ordinary repricing of the same era (last column): in 2021-2025 manufacturers "
              "raised prices by 3-7% per change with no tax change at all.",
              "- The ordinary-repricing column pools all regimes; it is not split by price level.",
              "- Pack size is assumed 20 when the listing prints none.",
              "- The window can include price changes with other causes (new formats, promotions, cost changes).", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    db = sqlite_utils.Database(sys.argv[1] if len(sys.argv) > 1 else "tobacco.db")
    rates, vat, changes = load(db)
    days = events(rates, vat)
    per_event, all_rows = [], []
    for day, group in assign(changes, days).items():
        old_r, new_r = rate_on(rates, day - timedelta(1)), rate_on(rates, day)
        old_v, new_v = vat_on(vat, day - timedelta(1)), vat_on(vat, day)
        rows = change_rows(group, old_r, new_r, old_v, new_v)
        what = (f"ad valorem {old_r.ad_valorem_pct:g}% -> {new_r.ad_valorem_pct:g}%, specific {old_r.specific:g} -> {new_r.specific:g}, "
                f"floor {old_r.minimum:g} -> {new_r.minimum:g}" + (f", VAT {old_v:g}% -> {new_v:g}%" if old_v != new_v else ""))
        per_event.append({"date": day.isoformat(), "what": what, "summary": summarise(rows)})
        all_rows += [{**r, "event": day.isoformat(), "published": r["published"].isoformat()} for r in rows]
    from statistics import median
    ordinary = baseline(changes, days, rates, vat)
    base = [{"year": y, "n": len(g), "median_actual_pct": median(r["actual_pct"] for r in g),
             "median_d_net": median(r["d_net"] for r in g)}
            for y in sorted({r["published"].year for r in ordinary})
            for g in [[r for r in ordinary if r["published"].year == y]]]
    db["result_passthrough_baseline"].insert_all(base, pk="year", replace=True)
    db["result_passthrough"].insert_all(
        ({"event": e["date"], **s} for e in per_event for s in e["summary"]), pk=("event", "regime_old"), replace=True)
    db["result_passthrough_changes"].insert_all(all_rows, replace=True)
    (HERE / "report.md").write_text(render(per_event, base), encoding="utf-8")
    print((HERE / "report.md").read_text())
