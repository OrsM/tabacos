"""python -m analyses.stockpiling.run [db] -> result_stockpiling table and report.md"""
import sys
from pathlib import Path

import sqlite_utils

from tabacos.workdays import working_days

from .model import swings, yoy_noise

HERE = Path(__file__).parent
EVENT_YEAR = 2025
VARIANTS = {                               # name -> trading days per month (None: raw packs)
    "raw packs": None,
    "per weekday": lambda y, m: working_days(y, m),
    "per Mon-Sat day": lambda y, m: working_days(y, m, saturdays=True),
}


def pct(x: float) -> str:
    return f"{x * 100:+.1f}%"


def pp(x: float) -> str:
    return f"{x * 100:+.1f}"


def tag(r: dict) -> str:
    return "tax rise" if r["is_event"] else "base effect of the stockpile" if r["after_event"] else "placebo"


def covid(year: int, month: int) -> bool:
    return (year, month) >= (2020, 3) and (year, month) <= (2021, 6)


def render(results: dict[str, list[dict]], noise: dict[str, float]) -> str:
    lines = ["# Stockpiling before the 1 January 2025 tax rise", "",
             "Generated by `python -m analyses.stockpiling.run`. See question.md for the method and its limits.", "",
             "## Summary: Dec/Jan swing (points) under three ways of counting days", "",
             "| Packs counted | Tax winter 2024/25 | Placebo winters | Tax winter Dec+Jan yoy |", "|---|---|---|---|"]
    for name, rows in results.items():
        event = next(r for r in rows if r["is_event"])
        placebos = [r for r in rows if not r["is_event"] and not r["after_event"]]
        lines.append(f"| {name} | {pp(event['swing'])} | " + ", ".join(pp(r["swing"]) for r in placebos)
                     + f" | {pct(event['net_yoy'])} |")
    lines += ["", "Which day count fits? Standard deviation of monthly year-on-year growth outside Covid "
              "(lower = the calendar explains more of the month-to-month movement):", ""]
    lines += [f"- {name}: {noise[name] * 100:.2f} points" for name in results]
    best = min(noise, key=noise.get)
    event = next(r for r in results[best] if r["is_event"])
    placebos = [r["swing"] for r in results[best] if not r["is_event"] and not r["after_event"]]
    verdict = "inside" if min(placebos) <= event["swing"] <= max(placebos) else "outside"
    lines += ["", f"**Reading (day count with the least noise: {best}):** the tax winter's swing is {pp(event['swing'])} points; "
              f"placebo winters range from {pp(min(placebos))} to {pp(max(placebos))}. The tax winter is {verdict} "
              "that range, so " + ("this series shows no detectable stockpiling." if verdict == "inside"
                                   else "the series shows a swing larger than any placebo.")]
    for name, rows in results.items():
        lines += ["", f"## {name}", "",
                  "| Winter | December yoy | January yoy | Swing (Dec - Jan) | Dec + Jan yoy | |", "|---|---|---|---|---|---|"]
        lines += [f"| Dec {r['year'] - 1} / Jan {r['year']} | {pct(r['pre_yoy'])} | {pct(r['post_yoy'])} "
                  f"| {pp(r['swing'])} pp | {pct(r['net_yoy'])} | {tag(r)} |" for r in rows]
    lines += ["", "## Notes", "",
              "- Placebo winters are those without a tax change on 1 January. Winter 2020/21 falls in the Covid restrictions.",
              "- Winter 2025/26 is not a placebo: its comparison base holds the stockpile.",
              "- Trading days: weekdays less Spain's national holidays (regional and local holidays are not modelled); "
              "whether tobacconists' orders follow weekdays or Mon-Sat is not known, hence both.",
              "- Few winters and one event: this shows a pattern, it does not estimate an effect size.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    db = sqlite_utils.Database(sys.argv[1] if len(sys.argv) > 1 else "tobacco.db")
    packs = {(r["year"], r["month"]): r["packs"] for r in db.query((HERE / "data.sql").read_text())}
    results, noise = {}, {}
    for name, count in VARIANTS.items():
        days = None if count is None else {k: count(*k) for k in packs}
        noise[name] = yoy_noise(packs, days, skip=covid)
        results[name] = swings(packs, pre_month=12, post_month=1, event_year=EVENT_YEAR, days=days)
    db["result_stockpiling"].insert_all(
        ({**r, "variant": name} for name, rows in results.items() for r in rows), pk=("year", "variant"), replace=True)
    (HERE / "report.md").write_text(render(results, noise), encoding="utf-8")
    print((HERE / "report.md").read_text())
