"""python -m analyses.panel.run [db] -> result_panel* tables, report.md and two figures"""
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt          # noqa: E402
import sqlite_utils                      # noqa: E402

from .model import differences, dispersion_by_month, within_slope   # noqa: E402

HERE = Path(__file__).parent
LAGS = (1, 3, 6, 12, 24)
EVENTS = {"2025-01": "tax rise, 1 Jan 2025"}
INK, MUTED, GRID, ACCENT = "#1f2328", "#59636e", "#e1e4e8", "#1f6feb"


def style(ax):
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(MUTED)
    ax.tick_params(colors=MUTED, labelsize=9)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def months_axis(months):
    return [int(m[:4]) + (int(m[5:]) - 1) / 12 for m in months]


def figure_dispersion(disp: dict[str, float]):
    months = sorted(disp)
    fig, ax = plt.subplots(figsize=(7, 3.2), dpi=150)
    ax.plot(months_axis(months), [disp[m] * 100 for m in months], color=ACCENT, linewidth=2)
    for m, label in EVENTS.items():
        x = months_axis([m])[0]
        ax.axvline(x, color=MUTED, linewidth=1, linestyle=(0, (4, 3)))
        ax.text(x - 0.08, ax.get_ylim()[1], label, ha="right", va="top", fontsize=9, color=MUTED)
    ax.set_ylabel("spread of prices across brands, %", color=MUTED, fontsize=9)
    ax.set_title("Brands' prices have spread out since 2021 (share-weighted sd of log price)", loc="left", fontsize=10, color=INK)
    style(ax)
    fig.tight_layout()
    fig.savefig(HERE / "dispersion.png")
    plt.close(fig)


def figure_slopes(fits: list[dict]):
    fig, ax = plt.subplots(figsize=(7, 3.2), dpi=150)
    xs = range(len(fits))
    ax.axhline(0, color=MUTED, linewidth=1)
    ax.errorbar(xs, [f["slope"] for f in fits], yerr=[2 * f["se"] for f in fits], fmt="o", color=ACCENT,
                ecolor=ACCENT, elinewidth=2, capsize=0, markersize=7, markeredgecolor="white", markeredgewidth=1.5)
    ax.set_xticks(list(xs), [f"{f['lag']} mo" for f in fits])
    ax.set_xlabel("months between the two observations", color=MUTED, fontsize=9)
    ax.set_ylabel("slope of log share on log relative price", color=MUTED, fontsize=9)
    ax.set_title("Every interval covers zero and a wide range of elasticities (point +/- 2 s.e.)", loc="left", fontsize=10, color=INK)
    style(ax)
    fig.tight_layout()
    fig.savefig(HERE / "slopes.png")
    plt.close(fig)


def step_note(rows, before="2022-11", after="2022-12") -> str:
    """Prices of a few brands either side of the December 2022 step, from the panel itself."""
    price = {(r["month"], r["brand"][0]): r["price"] for r in rows}
    parts = [f"{b.title()} {price[(before, b)]:.2f} -> {price[(after, b)]:.2f}"
             for b in ("MARLBORO", "CAMEL", "BULLBRAND") if (before, b) in price and (after, b) in price]
    return "; ".join(parts) + " (premium brands up about 6%, the cheap one flat)."


def render(rows, disp, fits, jumps) -> str:
    months = sorted({r["month"] for r in rows})
    lines = ["# Brand panel: price and share, a first look", "",
             "Generated by `python -m analyses.panel.run`. See question.md.", "",
             "## The panel", "",
             f"- {len(rows)} brand-months, {len({r['brand'] for r in rows})} brands, {len(months)} months ({months[0]} to {months[-1]}).",
             f"- Month-on-month change in a brand's price relative to the market: standard deviation "
             f"{fits[0]['sd_price_change'] * 100:.1f}%. Only {jumps[0]} of {jumps[1]} brand-month changes exceed 2%.", "",
             "Prices mostly move together. The variation that could identify an elasticity (a brand repricing against "
             "the others) is small next to the month-to-month noise in shares.", "",
             "## Is the spread of prices compressing?", "",
             "![Spread of prices across brands](dispersion.png)", "",
             f"Spread: {disp[months[0]] * 100:.1f}% in {months[0]}, {disp['2021-12'] * 100:.1f}% in 2021-12, "
             f"{disp['2024-12'] * 100:.1f}% in 2024-12, {disp['2025-01'] * 100:.1f}% in 2025-01, {disp['2025-03'] * 100:.1f}% in 2025-03, "
             f"{disp[months[-1]] * 100:.1f}% in {months[-1]}.", "",
             f"At the 1 January 2025 tax rise the spread stepped down from {disp['2024-12'] * 100:.1f}% to {disp['2025-01'] * 100:.1f}% "
             "and stayed there to March, which is the direction the tariff structure predicts (cheap packs rise most). "
             "Over 2021-2026 the spread widened overall. That measure mixes brands repricing with changes in which brands "
             "are on the list; I have not separated the two.",
             f"The largest single step, in December 2022, is repricing: {step_note(rows)}", "",
             "## Share against relative price", "",
             "![Slope of log share on log relative price, by horizon](slopes.png)", "",
             "| Months apart | n | Brands | Slope | s.e. (clustered by brand) | 95% interval |", "|---|---|---|---|---|---|"]
    lines += [f"| {f['lag']} | {f['n']} | {f['brands']} | {f['slope']:+.2f} | {f['se']:.2f} | "
              f"{f['slope'] - 2 * f['se']:+.1f} to {f['slope'] + 2 * f['se']:+.1f} |" for f in fits]
    lines += ["", "## Reading", "",
              "- A plain fixed-effects slope of share on relative price cannot tell an elasticity of -4 from +4 here. "
              "At short lags prices barely move; at long lags the estimate changes with the horizon and the intervals "
              "still cover zero.",
              "- This is a result about the data, not about smokers: national tax changes move all prices together, and "
              "brands rarely reprice against one another by more than a point or two a month.",
              "- Ways to get more out of it: model the mechanism (shares as a choice model with brand effects), use the "
              "tax-implied price change as an instrument for the part of a brand's repricing that the tax forces by tier, "
              "and bring in regional or age structure. Each needs its own identifying assumption, stated up front.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    db = sqlite_utils.Database(sys.argv[1] if len(sys.argv) > 1 else "tobacco.db")
    rows = [{"month": r["month"], "brand": (r["brand"], r["company"]), "price": r["price"], "share_pct": r["share_pct"]}
            for r in db.query("select month, brand, company, price, share_pct from brand_month where month >= '2018-01'")]
    fits = [{"lag": lag, **within_slope(differences(rows, lag))} for lag in LAGS]
    disp = dispersion_by_month(rows)
    d1 = differences(rows, 1)
    jumps = (sum(abs(d["dlog_price"]) > 0.02 for d in d1), len(d1))
    db["result_panel"].insert_all(fits, pk="lag", replace=True)
    db["result_panel_dispersion"].insert_all(({"month": m, "dispersion": v} for m, v in sorted(disp.items())), pk="month", replace=True)
    figure_dispersion(disp)
    figure_slopes(fits)
    (HERE / "report.md").write_text(render(rows, disp, fits, jumps), encoding="utf-8")
    print((HERE / "report.md").read_text())
